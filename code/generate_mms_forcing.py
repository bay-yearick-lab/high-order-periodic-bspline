"""Generate the manufactured-solution forcing header for the forced MMS.

Manufactured field (divergence-free by streamfunction, NON-gradient
nonlinearity so the projection cannot annihilate the convective error):

    psi = [sin(x + 0.7) sin(y + 0.3) + 0.5 sin(2x + 0.2) sin(y + 0.9)] cos(t)
    u   =  dpsi/dy,   v = -dpsi/dx,   w = 0   (z-invariant)

NOTE on the field choice: a single separable mode sin(ax+c) sin(by+d) is an
eigenfunction of the Laplacian, so omega = (a^2+b^2) psi and
u . grad omega = (a^2+b^2) u . grad psi = 0: its convective term is a pure
gradient and the projection removes it, making the forced test vacuous (the
symbolic gate below catches this). Two modes with distinct eigenvalues
(|k|^2 = 2 and 5) break the omega = f(psi) alignment.

Forcing convention: p_m = 0; the exact pressure-gradient role is folded into
the source, S = du/dt + (u . grad) u - nu lap u, and the discrete projection
determines the discrete pressure (standard forced-MMS practice).

The script
  1. verifies symbolically that div u = 0 and that the residual of the exact
     fields under the forced momentum equations is identically zero,
  2. verifies symbolically that the convective term is NOT a gradient
     (curl of (u.grad)u nonzero), i.e. the forced test genuinely exercises
     the convective operator,
  3. emits code/solver/mms_forcing.h with a single CSE-optimized evaluator
     (sympy ccode; no hand-derived calculus anywhere),
  4. prints reference values at 20 random (x, y, t) points for the
     independent C-vs-sympy validation (compare to 1e-14).

Usage:  uv run code/generate_mms_forcing.py
"""

import random
from pathlib import Path

import sympy as sp

HERE = Path(__file__).resolve().parent
OUT = HERE / "solver" / "mms_forcing.h"

x, y, t, nu = sp.symbols("x y t nu", real=True)

psi = (sp.sin(x + sp.Rational(7, 10)) * sp.sin(y + sp.Rational(3, 10))
       + sp.Rational(1, 2) * sp.sin(2 * x + sp.Rational(1, 5))
         * sp.sin(y + sp.Rational(9, 10))) * sp.cos(t)
u = sp.diff(psi, y)
v = -sp.diff(psi, x)

# --- symbolic checks -------------------------------------------------------
div = sp.simplify(sp.diff(u, x) + sp.diff(v, y))
assert div == 0, f"div u != 0: {div}"

conv_u = u * sp.diff(u, x) + v * sp.diff(u, y)
conv_v = u * sp.diff(v, x) + v * sp.diff(v, y)
curl_conv = sp.simplify(sp.diff(conv_v, x) - sp.diff(conv_u, y))
assert curl_conv != 0, "convective term is a gradient; forced test would be vacuous"

lap_u = sp.diff(u, x, 2) + sp.diff(u, y, 2)
lap_v = sp.diff(v, x, 2) + sp.diff(v, y, 2)
Su = sp.diff(u, t) + conv_u - nu * lap_u
Sv = sp.diff(v, t) + conv_v - nu * lap_v

res_u = sp.simplify(sp.diff(u, t) + conv_u - nu * lap_u - Su)
res_v = sp.simplify(sp.diff(v, t) + conv_v - nu * lap_v - Sv)
assert res_u == 0 and res_v == 0, "forced-equation residual not identically zero"

print("symbolic checks: div u == 0; forced residual == 0;")
print(f"  curl of convective term (must be nonzero): {sp.simplify(curl_conv)}")

# --- code generation (CSE) -------------------------------------------------
repl, reduced = sp.cse([u, v, Su, Sv], optimizations="basic")
lines = []
for sym, expr in repl:
    lines.append(f"    const double {sym} = {sp.ccode(expr)};")
names = ["*ue", "*ve", "*su", "*sv"]
for name, expr in zip(names, reduced):
    lines.append(f"    {name} = {sp.ccode(expr)};")
body = "\n".join(lines)

header = f"""// mms_forcing.h -- GENERATED by code/generate_mms_forcing.py (sympy). Do not
// hand-edit. Manufactured solution and momentum source for the forced MMS:
//   psi = [sin(x+0.7) sin(y+0.3) + 0.5 sin(2x+0.2) sin(y+0.9)] cos(t),
//   u = psi_y,  v = -psi_x,  w = 0,
//   S   = u_t + (u.grad)u - nu lap(u)   (p_m = 0; the projection determines
//                                        the discrete pressure).
// Two modes with distinct Laplacian eigenvalues (|k|^2 = 2, 5) so the
// convective term is NOT a gradient (a single separable mode would make it
// one, and the projection would erase it -- the vacuous-test trap).
// Verified in the generator: div u == 0 and the forced residual == 0
// symbolically; the convective term is not a gradient (nonzero curl), so the
// forced problem genuinely exercises the convective operator.

#ifndef MMS_FORCING_H
#define MMS_FORCING_H

#include <cmath>

static inline void mms_forced_eval(double x, double y, double t, double nu,
                                   double* ue, double* ve,
                                   double* su, double* sv) {{
{body}
}}

#endif // MMS_FORCING_H
"""
OUT.write_text(header)
print(f"wrote {OUT}")

# --- reference values for the independent C validation ----------------------
fu, fv, fsu, fsv = (sp.lambdify((x, y, t, nu), e, "mpmath") for e in (u, v, Su, Sv))
random.seed(20260707)
print("\nVALIDATION_POINTS (x y t nu u v su sv):")
import mpmath
mpmath.mp.dps = 30
for _ in range(20):
    xx = random.uniform(0, 2 * 3.14159265)
    yy = random.uniform(0, 2 * 3.14159265)
    tt = random.uniform(0, 1)
    nn = 1e-4
    vals = [f(xx, yy, tt, nn) for f in (fu, fv, fsu, fsv)]
    print("  %.17g %.17g %.17g %.17g %s" % (xx, yy, tt, nn,
          " ".join("%.17g" % float(vv) for vv in vals)))
